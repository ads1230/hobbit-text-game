# Builds web/js/data.js: the game's own pictures, sounds, fonts, patterns and the
# data-fork tables (opponent parameters, roster), packed for the JavaScript port.
#   python3 -I tools/build_data.py <extracted dir (from tools/extract.py)> [js/data.js]
import os, sys, json, struct, base64
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1]
RES = os.path.join(SRC, 'res')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'js', 'data.js')

def b64(b): return base64.b64encode(bytes(b)).decode('ascii')

def res_files(t):
    d = os.path.join(RES, t)
    out = {}
    for f in os.listdir(d):
        if not f.endswith('.bin'): continue
        rid = int(f.split('.')[0].split('_')[0])
        out[rid] = open(os.path.join(d, f), 'rb').read()
    return out

# --- pictures: raw PICT resources (decoded by the page) ---
picts = res_files('PICT')
# --- sounds: 'ASND' resources (FFSynthRec: mode.w, count.l, samples) -> samples from offset 6 ---
asnd = res_files('ASND')
sounds = {str(k): b64(v[6:]) for k, v in asnd.items()}
# data fork: 9 x 70-byte opponent records, roster block, 3 synth records
data = open(os.path.join(SRC, 'app', 'data.bin'), 'rb').read()
params = [list(struct.unpack('>35h', data[i*70:(i+1)*70])) for i in range(9)]
p = 630
champ = data[p:p+32]
roster = []
for i in range(20):
    s = data[p+32+32*i:p+64+32*i]
    roster.append([s[1:1+s[0]].decode('mac_roman'), struct.unpack('>h', data[p+672+2*i:p+674+2*i])[0]])
p = 630 + 712
for name in ['wall', 'hit', 'crack']:
    n = struct.unpack('>I', data[p:p+4])[0]
    sounds[name] = b64(data[p+4+6:p+4+n]); p += 4 + n
# --- patterns ---
pats = {k: list(v) for k, v in res_files('PAT_').items()}
# --- fonts ---
def font(b):
    ft, first, last, widMax, kernMax, nDesc, frw, frh, owT, asc, desc, lead, roww = struct.unpack('>HHHHhhHHHHHHH', b[:26])
    n = last - first + 3
    img = b[26:26 + roww * 2 * frh]
    loc = struct.unpack('>%dH' % n, b[26 + roww*2*frh: 26 + roww*2*frh + 2*n])
    owp = 16 + owT * 2   # owTLoc is relative to the owTLoc field itself (offset 16)
    ow = struct.unpack('>%dH' % n, b[owp: owp + 2*n])
    glyphs = {}
    for c in range(first, last + 2):   # last+1 = missing-symbol glyph
        i = c - first
        o = ow[i]
        if o == 0xFFFF: continue
        offset, width = (o >> 8) & 0xFF, o & 0xFF
        x0, x1 = loc[i], loc[i+1]
        cols = []
        for x in range(x0, x1):
            col = 0
            for y in range(frh):
                byte = img[y * roww * 2 + (x >> 3)]
                if (byte >> (7 - (x & 7))) & 1: col |= (1 << y)
            cols.append(col)
        glyphs[c] = [kernMax + offset, width, cols]   # left bearing = kernMax + offset; width = advance
    return dict(height=frh, ascent=asc, descent=desc, leading=lead, kernMax=kernMax, widMax=widMax, first=first, last=last, glyphs=glyphs)
fonts = {}
for fid, name in [(1548, 'la12'), (29452, 'sq12'), (29458, 'sq18')]:
    fonts[name] = font(open(os.path.join(RES, 'FONT', '%d.bin' % fid), 'rb').read())
# --- strings ---
strs = open(os.path.join(RES, 'STRS', '0.bin'), 'rb').read()
def pstr(off):
    return strs[off+1:off+1+strs[off]].decode('mac_roman')
# --- write ---
with open(OUT, 'w') as f:
    f.write('// Game data from the Macintosh release of Shufflepuck Café (© 1988 Brøderbund Software):\n')
    f.write('// PICT resources (decoded by pict.js), sampled sounds, bitmap fonts, patterns and the\n')
    f.write('// data-fork tables (opponent parameters and the default roster). Generated by tools/build_data.py.\n')
    f.write('var SPC_DATA = {\n')
    f.write('picts: {' + ','.join('%d:"%s"' % (k, b64(v)) for k, v in sorted(picts.items())) + '},\n')
    f.write('sounds: {' + ','.join('"%s":"%s"' % (k, v) for k, v in sorted(sounds.items())) + '},\n')
    f.write('params: ' + json.dumps(params) + ',\n')
    f.write('champion: ' + json.dumps(champ[1:1+champ[0]].decode('mac_roman')) + ',\n')
    f.write('roster: ' + json.dumps(roster) + ',\n')
    f.write('patterns: {' + ','.join('%d:%s' % (k, json.dumps(v)) for k, v in sorted(pats.items())) + '},\n')
    f.write('fonts: ' + json.dumps(fonts, separators=(',', ':')) + '\n')
    f.write('};\n')
print('wrote', OUT, os.path.getsize(OUT))
