  function stamp(screen, x, y, text, inverse) {
    var bytes = screen.bytes;
    for (var k = 0; k < text.length; k++) {
      var g = glyphs[text.charAt(k)] || glyphs['?'], gx = x + k * 7;
      for (var r = 0; r < 7; r++) {
        var row = g[r], sy = y + r; if (!row || sy < 0 || sy >= 192) continue;
        for (var i = 0; i < 6; i++) {
          if (!((row >> i) & 1) && !((row >> (i - 1)) & 1)) continue;
          var sx = gx + i; if (sx < 0 || sx >= 280) continue;
          var idx = sy * 40 + ((sx / 7) | 0), bit = 1 << (sx % 7);
          if (inverse) bytes[idx] &= ~bit; else bytes[idx] |= bit;
        }
      }
    }
  }
  return { stamp: stamp };
