  // glyph rows as 7-bit masks (a blank dot each side of the 5-dot shape)
  var GLYPH = new Uint8Array(128 * 8);
  for (var ch = 32; ch < 127; ch++) {
    var rows = (G[String.fromCharCode(ch)] || G['?']).split('|');
    for (var r = 0; r < 7; r++) { var b = 0; for (var i = 0; i < 5; i++) if (rows[r].charAt(i) === '#') b |= 1 << (i + 1); GLYPH[ch * 8 + r] = b; }
  }
  // the low-resolution palette (the sixteen colours as a monitor would show them)
  var LORES = [[0, 0, 0], [227, 30, 96], [96, 78, 189], [255, 68, 253], [0, 163, 96], [156, 156, 156], [20, 207, 253], [208, 195, 255],
    [96, 114, 3], [255, 106, 60], [156, 156, 156], [255, 160, 208], [20, 245, 60], [208, 221, 141], [114, 255, 208], [255, 255, 255]];
  var HI = { white: [255, 255, 255], violet: [221, 68, 221], green: [40, 200, 60], blue: [40, 150, 240], orange: [240, 120, 40] };
  var MONO = [96, 255, 128];                                          // a green phosphor, for the monochrome setting

  function Video(machine) {
    this.m = machine; this.image = null; this.mono = false; this.flashOn = true;
    this.bits = new Uint8Array(282); this.hb = new Uint8Array(282);
  }
  Video.prototype.attach = function (ctx) { this.ctx = ctx; this.image = ctx.createImageData(280, 192); this.data = this.image.data; };
  Video.prototype.attachBuffer = function (rgba) { this.ctx = null; this.image = null; this.data = rgba; };
  // one row of hi-res bytes to colour
  Video.prototype.hiresLine = function (src, off, y) {
    var bits = this.bits, hb = this.hb, d = this.data, mono = this.mono, W = 280;
    for (var c = 0; c < 40; c++) { var b = src[off + c]; for (var i = 0; i < 7; i++) { bits[1 + c * 7 + i] = (b >> i) & 1; hb[1 + c * 7 + i] = b >> 7; } }
    bits[0] = 0; bits[W + 1] = 0;
    var p = y * W * 4;
    for (var x = 0; x < W; x++, p += 4) {
      var i = x + 1, col = null;
      if (mono) { if (bits[i]) col = MONO; }
      else if (bits[i]) col = (bits[i - 1] || bits[i + 1]) ? HI.white : ((x & 1) ? (hb[i] ? HI.orange : HI.green) : (hb[i] ? HI.blue : HI.violet));
      else if (bits[i - 1] && bits[i + 1]) col = ((x - 1) & 1) ? (hb[i] ? HI.orange : HI.green) : (hb[i] ? HI.blue : HI.violet);
      if (col) { d[p] = col[0]; d[p + 1] = col[1]; d[p + 2] = col[2]; } else { d[p] = 0; d[p + 1] = 0; d[p + 2] = 0; }
      d[p + 3] = 255;
    }
  };
  Video.prototype.textRow = function (src, base, row, lores) {
    var d = this.data, m = this.m, mono = this.mono;
    var addr = base + (row & 7) * 0x80 + (row >> 3) * 0x28;
    for (var col = 0; col < 40; col++) {
      var v = src[addr + col], x0 = col * 7;
      if (lores) {
        var top = LORES[v & 15], bot = LORES[v >> 4];
        if (mono) { top = (v & 15) ? MONO : LORES[0]; bot = (v >> 4) ? MONO : LORES[0]; }
        for (var yy = 0; yy < 8; yy++) { var c = yy < 4 ? top : bot, p = ((row * 8 + yy) * 280 + x0) * 4; for (var xx = 0; xx < 7; xx++, p += 4) { d[p] = c[0]; d[p + 1] = c[1]; d[p + 2] = c[2]; d[p + 3] = 255; } }
        continue;
      }
      // the character sets: inverse, flashing (or, with ALTCHAR, inverse lower case) and normal
      var inverse = false, ch;
      if (v < 0x20) { inverse = true; ch = v + 0x40; }
      else if (v < 0x40) { inverse = true; ch = v; }
      else if (v < 0x60) { ch = v; inverse = m.altchar ? true : this.flashOn; }
      else if (v < 0x80) { ch = m.altchar ? v : v - 0x40; inverse = m.altchar ? true : this.flashOn; }
      else if (v < 0xA0) ch = v - 0x40;
      else ch = v - 0x80;
      var g = ch * 8;
      for (yy = 0; yy < 8; yy++) {
        var bitsRow = yy < 7 ? GLYPH[g + yy] : 0, p2 = ((row * 8 + yy) * 280 + x0) * 4;
        for (xx = 0; xx < 7; xx++, p2 += 4) { var on = ((bitsRow >> xx) & 1) ^ (inverse ? 1 : 0), c2 = on ? (mono ? MONO : HI.white) : LORES[0]; d[p2] = c2[0]; d[p2 + 1] = c2[1]; d[p2 + 2] = c2[2]; d[p2 + 3] = 255; }
      }
    }
  };
  Video.prototype.render = function () {
    var m = this.m, main = m.main, aux = m.aux;
    var page2 = m.page2 && !m.store80;
    var textRows = m.textMode ? 24 : (m.mixed ? 4 : 0), gfxRows = 24 - textRows;
    if (!m.textMode && m.hires) {
      var base = page2 ? 0x4000 : 0x2000;
      for (var y = 0; y < gfxRows * 8; y++) this.hiresLine(main, base + (y & 7) * 0x400 + ((y >> 3) & 7) * 0x80 + (y >> 6) * 0x28, y);
    } else if (!m.textMode) {
      for (var r = 0; r < gfxRows; r++) this.textRow(main, page2 ? 0x800 : 0x400, r, true);
    }
    for (r = gfxRows; r < 24; r++) this.textRow(main, page2 ? 0x800 : 0x400, r, false);
    if (this.ctx) this.ctx.putImageData(this.image, 0, 0);
  };
  Video.GLYPH = GLYPH; Video.LORES = LORES;
